using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Pixely.Ecs.Generator;

readonly record struct RelationshipExtraction(string? Relationship, DiagnosticInfo? Diagnostic);

// Registers every struct of the assembly that implements IRelationship, through a module initializer, because the world cannot read the target of a
// component it knows only as an unconstrained T without boxing it.
[Generator]
public class RelationshipGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<RelationshipExtraction?> results = context.SyntaxProvider.CreateSyntaxProvider(
            predicate: static (node, _) => node is TypeDeclarationSyntax { BaseList: not null } and (StructDeclarationSyntax or RecordDeclarationSyntax),
            transform: static (ctx, ct) => Extract(ctx, ct)).Where(static result => result is not null);

        context.RegisterSourceOutput(results.Collect(), static (spc, results) =>
        {
            SortedSet<string> relationships = new SortedSet<string>(StringComparer.Ordinal);
            foreach (RelationshipExtraction? result in results)
            {
                if (result!.Value.Diagnostic is { } diagnostic)
                {
                    GeneratorSupport.Report(spc, diagnostic);
                }
                else
                {
                    relationships.Add(result.Value.Relationship!);
                }
            }

            if (relationships.Count > 0)
            {
                spc.AddSource("Relationships.g.cs", Generate(relationships));
            }
        });
    }

    private static RelationshipExtraction? Extract(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        TypeDeclarationSyntax syntax = (TypeDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(syntax, cancellationToken) is not INamedTypeSymbol { TypeKind: TypeKind.Struct } type || !GeneratorSupport.IsRelationship(type))
        {
            return null;
        }

        // A partial relationship registers once, from its first declaration that has a base list.
        if (type.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax(cancellationToken)).OfType<TypeDeclarationSyntax>().First(declaration => declaration.BaseList is not null) != syntax)
        {
            return null;
        }

        // The generated code is outside the relationship, and a tag has no column to hold the target.
        Compilation compilation = context.SemanticModel.Compilation;
        if (GeneratorSupport.ContainsTypeParameter(type) || type.IsGenericType || IsInFileLocalType(type) || !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
            || type.IsRefLikeType || GeneratorSupport.IsTag(type))
        {
            return new RelationshipExtraction(null, GeneratorSupport.CreateDiagnostic("PXECS017",
                $"The relationship {type.Name} must be a struct that is not a tag or a ref struct, without type parameters, accessible anywhere in its assembly.", syntax.Identifier.GetLocation()));
        }

        return new RelationshipExtraction(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), null);
    }

    private static bool IsInFileLocalType(INamedTypeSymbol type) => type.IsFileLocal || (type.ContainingType is not null && IsInFileLocalType(type.ContainingType));

    private static string Generate(IEnumerable<string> relationships)
    {
        StringBuilder sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Pixely.Ecs.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class RelationshipRegistration");
        sb.AppendLine("    {");
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Register()");
        sb.AppendLine("        {");
        foreach (string relationship in relationships)
        {
            sb.AppendLine($"            global::Pixely.Ecs.Relationships.Register<{relationship}>();");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
